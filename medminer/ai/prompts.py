def build_user_message(task: str, context: str, question: str = "") -> str:
    instr = TASKS[task][1]
    parts = []
    if instr:
        parts.append(instr)
    if question.strip():
        parts.append(f"用户补充问题：{question.strip()}")
    if context.strip():
        parts.append("以下是分析结果的统计摘要（不含原始患者数据）：\n\n" + context)
    return "\n\n".join(parts)
